"""V2 P4: the purchase register's workbook and its comparison with GSTR-2B, from rows made
here (the database path is tested in tests/integration/test_purchase_register.py)."""

import io
import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any
from zoneinfo import ZoneInfo

import pytest

from docforge.gstr2b import TwoBInvoice
from docforge.purchase_register import (
    ABOUT,
    HEADERS,
    Register,
    RegisterInvalid,
    RegisterRow,
    _totals,
    compare_2b,
    month_bounds,
    write_workbook,
)
from docforge.trust.duplicates import text_key


def row(gstin: str, number: str, taxable: str, cgst: str = "0", sgst: str = "0",
        igst: str = "0", total: str | None = None, name: str = "Synthetic Seller",
        note: str = "") -> RegisterRow:  # fmt: skip
    tax = Decimal(cgst) + Decimal(sgst) + Decimal(igst)
    return RegisterRow(
        document_id=uuid.uuid4(), supplier_gstin=gstin, supplier_name=name, invoice_no=number,
        invoice_date=date(2026, 11, 5), place_of_supply="24", taxable_value=Decimal(taxable),
        cgst=Decimal(cgst), sgst=Decimal(sgst), igst=Decimal(igst),
        invoice_total=Decimal(total) if total else Decimal(taxable) + tax, note=note,
    )  # fmt: skip


def register(*rows: RegisterRow) -> Register:
    return Register(date(2026, 11, 1), None, rows, _totals(rows))


def sheets(data: bytes) -> Any:
    from openpyxl import load_workbook

    return load_workbook(io.BytesIO(data))


ROWS = (
    row("24AABFN7754K1Z0", "NVM/101", "540.00", cgst="19.80", sgst="19.80", total="580.00"),
    row("27AAACS1234F1ZS", "000123", "850.00", igst="102.00"),
    row("24AABFN7754K1Z0", "NVM/102", "1000.00", cgst="40.00", sgst="40.00"),
)


def test_one_row_per_invoice_in_the_columns_order_with_a_totals_row() -> None:
    book = sheets(write_workbook(register(*ROWS), workspace="Synthetic", person="Asha Rao"))

    assert book.sheetnames == ["Purchase Register", "About"]
    values = [[c.value for c in r] for r in book["Purchase Register"].iter_rows()]
    assert tuple(values[0]) == HEADERS
    assert len(values) == 1 + 3 + 1  # header, three invoices, totals
    totals = values[-1]
    assert totals[0] == "Total"
    for column in range(5, 11):  # Taxable .. Invoice Total
        expected = sum(Decimal(str(r[column])) for r in values[1:4])
        assert Decimal(str(totals[column])) == expected
    assert values[2][6:9] == [0, 0, 102]  # IGST only across states


def test_money_is_numbers_dates_are_dates_and_identifiers_are_text() -> None:
    book = sheets(write_workbook(register(*ROWS), workspace="Synthetic", person="Asha Rao"))
    sheet = book["Purchase Register"]

    second = [sheet.cell(row=3, column=c) for c in range(1, 14)]
    assert second[0].data_type == "s" and second[0].value == "27AAACS1234F1ZS"
    assert second[2].data_type == "s" and second[2].value == "000123"  # leading zeros kept
    assert second[3].is_date and second[3].value == datetime(2026, 11, 5)
    assert second[3].number_format == "dd-mmm-yyyy"
    assert second[4].data_type == "s" and second[4].value == "24"
    for money in second[5:11]:
        assert money.data_type == "n" and money.number_format == "#,##0.00"
    assert sheet.cell(row=5, column=6).data_type == "n"  # the totals row too


@pytest.mark.parametrize("start", ["=", "+", "-", "@"])
def test_a_name_that_starts_like_a_formula_is_text_never_a_formula(start: str) -> None:
    name = f'{start}HYPERLINK("x")'
    hostile = row("24AABFN7754K1Z0", "NVM/9", "1.00", name=name)

    book = sheets(write_workbook(register(hostile), workspace="Synthetic", person="Asha"))
    cell = book["Purchase Register"].cell(row=2, column=2)

    assert cell.data_type == "s" and cell.value == name


def test_the_about_sheet_says_what_the_file_is_and_is_not() -> None:
    made = datetime(2026, 11, 3, 12, 0, tzinfo=ZoneInfo("Asia/Kolkata"))

    data = write_workbook(register(*ROWS), workspace="Synthetic Pharma", person="Asha Rao",
                          now=made)  # fmt: skip
    texts = [c.value for r in sheets(data)["About"].iter_rows() for c in r if c.value]

    assert texts[:12] == ["Month", "November 2026", "Workspace", "Synthetic Pharma",
                          "Generated at", "03 Nov 2026, 12:00 IST", "Generated by", "Asha Rao",
                          "Invoice count", "3", "Supplier", "All suppliers"]  # fmt: skip
    assert ABOUT in texts
    assert any("not tax advice" in t for t in texts)
    assert any("Credit and debit notes are not included" in t for t in texts)


# AC-P4-5: the 2B check


def twob(gstin: str, number: str, taxable: str, cgst: str = "0", sgst: str = "0",
         igst: str = "0", value: str | None = None) -> TwoBInvoice:  # fmt: skip
    tax = Decimal(cgst) + Decimal(sgst) + Decimal(igst)
    return TwoBInvoice(
        supplier_gstin=gstin, trade_name=None, invoice_no=number, invoice_date=None,
        invoice_value=Decimal(value) if value else Decimal(taxable) + tax,
        taxable_value=Decimal(taxable), igst=Decimal(igst), cgst=Decimal(cgst),
        sgst=Decimal(sgst), rows=1, keys=(text_key(gstin) or "", text_key(number) or ""),
    )  # fmt: skip


def test_the_2b_check_classifies_matched_differing_missing_and_extra() -> None:
    found = compare_2b(register(*ROWS), [
        twob("24aabfn7754k1z0", "nvm/ 101", "540.00", cgst="19.80", sgst="19.80",
             value="580.50"),  # within a rupee; its number spaced and in lower case
        twob("27AAACS1234F1ZS", "000123", "600.00", igst="102.00", value="702.00"),
        twob("29AAGCB1286Q1ZT", "EXTRA/1", "10.00"),
    ])  # fmt: skip

    assert [m.status for m in found.rows] == ["matched", "amount_differs", "docforge_only"]
    assert found.rows[1].differences == {
        "taxable_value": Decimal("250.00"), "invoice_total": Decimal("250.00")
    }  # fmt: skip
    assert [m.twob.invoice_no for m in found.twob_only if m.twob] == ["EXTRA/1"]
    assert (found.count("matched"), found.count("twob_only")) == (1, 1)


def test_a_difference_of_exactly_a_rupee_matches_and_more_does_not() -> None:
    one = register(row("24AABFN7754K1Z0", "A1", "100.00"))

    within = compare_2b(one, [twob("24AABFN7754K1Z0", "A1", "101.00", value="100.00")])
    beyond = compare_2b(one, [twob("24AABFN7754K1Z0", "A1", "101.01", value="100.00")])

    assert within.rows[0].status == "matched"
    assert beyond.rows[0].status == "amount_differs"


def test_the_2b_check_sheet_is_added_to_the_file() -> None:
    found = compare_2b(register(*ROWS), [twob("29AAGCB1286Q1ZT", "EXTRA/1", "10.00")])

    book = sheets(write_workbook(register(*ROWS), workspace="S", person="A", comparison=found))
    values = [[c.value for c in r] for r in book["2B check"].iter_rows()]

    assert book.sheetnames == ["Purchase Register", "About", "2B check"]
    assert [v[0] for v in values[1:5]] == ["In DocForge only"] * 3 + ["In 2B only"]
    assert "Not a reconciliation with the GST portal" in str(values[-1][0])


@pytest.mark.parametrize("month", ["2026-13", "26-11", "november", "1999-12"])
def test_a_month_that_is_no_month_is_refused_in_words(month: str) -> None:
    with pytest.raises(RegisterInvalid):
        month_bounds(month)


def test_a_month_runs_from_its_first_day_to_its_last() -> None:
    assert month_bounds("2026-11") == (date(2026, 11, 1), date(2026, 11, 30))
    assert month_bounds("2028-02") == (date(2028, 2, 1), date(2028, 2, 29))
